# Helper: convert to LM19 measurement point format
# ============================================================================

def to_lm19_points(dataset, uh=6.3, ih=0.0):
    """Convert reference dataset to LM19 measurement point dicts.

    Returns list of {"ua", "ug1", "ug2", "ia", "ig2", "uh", "ih"}.
    For triodes, ug2=0 and ig2=0.
    """
    points = []
    n = len(dataset["ua"])
    is_pentode = dataset["topology"] == TOPOLOGY_PENTODE

    for i in range(n):
        p = {
            "ua":  dataset["ua"][i],
            "ug1": dataset["ug1"][i],
            "ug2": dataset["ug2"][i] if is_pentode else 0.0,
            "ia":  dataset["ia"][i],
            "ig2": dataset.get("ig2", [0.0] * n)[i] if is_pentode else 0.0,
            "uh":  uh,
            "ih":  ih,
        }
        points.append(p)
    return points
